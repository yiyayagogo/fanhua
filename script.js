function getListQuery(params) {
  return {
    cat: params.get('cat') || '',
    sub: params.get('sub') || '',
    q: (params.get('q') || '').trim(),
    tags: (params.get('tags') || '').split(',').map((tag) => tag.trim()).filter(Boolean),
    sort: params.get('sort') === 'name' ? 'name' : 'category'
  };
}

function allTags(product) {
  return [...product.tags.courses, ...product.tags.contests, ...product.tags.positions];
}

function matchesQuery(product, query) {
  if (query.cat && product.category !== query.cat) return false;
  if (query.sub && product.subCategory !== query.sub) return false;
  if (query.tags.length) {
    const productTags = allTags(product);
    if (!query.tags.some((tag) => productTags.includes(tag))) return false;
  }
  if (query.q) {
    const keyword = query.q.toLowerCase();
    const haystack = [
      product.name, product.model, product.category, product.subCategory,
      product.summary || '', ...allTags(product)
    ].join(' ').toLowerCase();
    if (!haystack.includes(keyword)) return false;
  }
  return true;
}

function sortProducts(list, sort) {
  const order = new Map(CATEGORIES.map((cat, index) => [cat.name, index]));
  return list.slice().sort((a, b) => {
    if (sort === 'name') return a.name.localeCompare(b.name, 'zh-Hans-CN');
    const catDiff = (order.get(a.category) || 0) - (order.get(b.category) || 0);
    if (catDiff !== 0) return catDiff;
    return a.name.localeCompare(b.name, 'zh-Hans-CN');
  });
}

