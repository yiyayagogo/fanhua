function updateListQuery(patch) {
  const current = getListQuery(parseHash().params);
  const next = { ...current, ...patch };
  const params = new URLSearchParams();
  if (next.q) params.set('q', next.q);
  if (next.cat) params.set('cat', next.cat);
  if (next.sub) params.set('sub', next.sub);
  if (next.tags && next.tags.length) params.set('tags', next.tags.join(','));
  if (next.sort && next.sort !== 'category') params.set('sort', next.sort);
  const hash = '#/list' + (params.toString() ? '?' + params.toString() : '');
  if (location.hash === hash) {
    renderList(parseHash().params);
  } else {
    location.hash = hash;
  }
}

