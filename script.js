function parseHash() {
  const raw = location.hash.replace(/^#/, '') || '/home';
  const queryIndex = raw.indexOf('?');
  const path = queryIndex >= 0 ? raw.slice(0, queryIndex) : raw;
  const params = new URLSearchParams(queryIndex >= 0 ? raw.slice(queryIndex + 1) : '');
  return { path: path || '/home', params };
}

function currentPath() {
  return document.body.dataset.route ? '/' + document.body.dataset.route : parseHash().path;
}

function showPage(id) {
  $$('.page').forEach((page) => page.classList.toggle('active', page.id === id));
}

let previousBasePath = null;

function renderRoute(scroll = true) {
  const { path, params } = parseHash();
  let route = path === '/' || path === '' ? '/home' : path;

  let basePath = route;
  let detailId = null;
  const detailMatch = route.match(/^\/detail\/([^/]+)$/);
  if (detailMatch) {
    basePath = '/detail';
    detailId = decodeURIComponent(detailMatch[1]);
  }

  document.body.dataset.route = basePath.slice(1);

  if (basePath === '/home') {
    renderHome();
    showPage('page-home');
    document.title = '智教实训装备 · 教育实训产品选购平台';
  } else if (basePath === '/list') {
    renderList(params);
    showPage('page-list');
    document.title = '产品中心 · 智教实训装备';
  } else if (basePath === '/detail') {
    renderDetail(detailId);
    showPage('page-detail');
  } else if (basePath === '/compare') {
    renderCompare();
    showPage('page-compare');
    document.title = '产品对比 · 智教实训装备';
  } else if (basePath === '/cart') {
    renderCart();
    showPage('page-cart');
    document.title = '选购清单 · 智教实训装备';
  } else if (basePath === '/share') {
    renderShare(params);
    showPage('page-share');
    document.title = '分享方案 · 智教实训装备';
  } else {
    location.hash = '#/home';
    return;
  }

  setMenuOpen(false);
  if (scroll) {
    const sameList = basePath === '/list' && previousBasePath === '/list';
    if (!sameList) window.scrollTo({ top: 0, behavior: 'auto' });
  }
  previousBasePath = basePath;
  updateBadges();
}

